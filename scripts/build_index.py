"""Regenerate docs/project-memory/INDEX.md from the record files.

Generated, never hand-edited. Run after adding records, or let the Stop hook
remind you. Safe to run repeatedly.
"""

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _ledger as L  # noqa: E402

# Any file carrying this marker was written by this script and may be replaced.
# A file without it was written by someone else and is never overwritten.
MARKER = "Generated by `scripts/build_index.py`"

HEADER = f"""# Ledger index

{MARKER}. Do not edit by hand.

Read `00-PROJECT-STATE.md` first; this is the map, not the briefing.
"""


def _relative(record):
    """Link target, relative to wherever the index itself lives."""
    try:
        return os.path.relpath(record, L.path_for("index").parent).replace("\\", "/")
    except Exception:
        return record.name


def section(kind, heading, note):
    rows = []
    for p in L.records(kind):
        fm = L.frontmatter(p)
        rid = fm.get("id", p.stem)
        status = fm.get("status", "?")
        date = fm.get("date", "")
        extra = ""
        if fm.get("superseded_by") not in (None, "", "null"):
            extra = f" -> superseded by {fm['superseded_by']}"
        rel = _relative(p)
        rows.append(f"| [{rid}]({rel}) | {L.title_of(p)} | {status}{extra} | {date} |")
    if not rows:
        return f"\n## {heading}\n\n{note}\n\n_None recorded yet._\n"
    return (
        f"\n## {heading}\n\n{note}\n\n"
        "| ID | Title | Status | Date |\n|---|---|---|---|\n" + "\n".join(rows) + "\n"
    )


def main():
    if not L.ledger_exists():
        print("no ledger found in this project", file=sys.stderr)
        return 1

    target = L.path_for("index")
    target.parent.mkdir(parents=True, exist_ok=True)
    # Never overwrite a file this script did not write. A project may already
    # keep its own INDEX.md, and clobbering it would destroy work silently.
    if target.is_file():
        try:
            existing = target.read_text(encoding="utf-8", errors="replace")
        except Exception:
            existing = ""
        if MARKER not in existing:
            print(
                f"refusing to overwrite {target}: it was not generated by this "
                "script.\nMove or rename it first if you want a generated index.",
                file=sys.stderr,
            )
            return 1

    out = [HEADER]
    out.append(section("adr", "Decisions", "What was chosen, and why."))
    out.append(
        section(
            "rej",
            "Rejections",
            "Settled arguments. **Read these before proposing anything new.**",
        )
    )
    out.append(section("cr", "Change requests", "Scope changes and their impact."))
    (L.ledger_dir() / "INDEX.md").write_text(
        "\n".join(out), encoding="utf-8", newline="\n"
    )
    print(L.ledger_dir() / "INDEX.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
